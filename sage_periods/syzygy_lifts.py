r"""Shared staircase enumeration and profile-selected syzygy lifts.

The routines depend on the reduction context through its data fields, not on
``rham_koszul`` or ``linear_closure``. Both engines use the same selection.
"""

# Cache for the staircase of basis_syzygies, keyed by the
# leading-monomial data (exponent vectors) of the syzygy Groebner basis and of
# the trivial syzygy module, together with the requested degree.  Exponent
# vectors do not depend on the coefficient field, so this cache is valid
# across evaluation points and across primes.  (At a degenerate evaluation
# point the leading monomial data, and hence the key, differs, so nothing
# wrong is returned from the cache.)
_staircase_cache = {}

def _diff_stairs(a, B, vars, deg):
    r"""
    Compute the degree ``deg`` staircase descendants of the monomial ``a`` modulo ``B``.

    This is a degree-by-degree staircase walk. Starting from ``a``, it multiplies by
    the variables in ``vars`` until total degree ``deg`` is reached, reducing modulo the
    forbidden monomials ``B`` at each stage. The result is a monomial basis for the
    relevant degree slice outside the leading-monomial ideal generated by ``B``.

    INPUT:

    * ``a`` -- A monomial, represented as an element of a Sage multivariate polynomial ring.
    * ``B`` -- A list of polynomials or monomials in the same ring, forming a Groebner basis, 
      used through their leading monomials as the forbidden staircase boundary.
    * ``vars`` -- A list of generators of ``parent(a)`` used to build staircase descendants.
    * ``deg`` -- A non-negative integer specifying the target total degree.

    OUTPUT:

    * ``descendants`` -- A Python ``set`` of monomials in ``parent(a)`` giving the
      admissible degree ``deg`` descendants of ``a`` modulo ``B``.
    """
    # Work on exponent vectors: membership of a monomial in a monomial ideal
    # is just divisibility by one of its generators, so no polynomial
    # arithmetic is needed.
    ring = a.parent()
    a_exp = a.exponents()[0]
    forbidden = [b.exponents()[0] for b in B]
    var_exps = [v.exponents()[0] for v in vars]

    def _reducible(m):
        return any(b.divides(m) for b in forbidden)

    d0 = sum(a_exp)
    if deg < d0:
        # No descendant can have smaller total degree than the starting monomial.
        return set()
    current = set() if _reducible(a_exp) else {a_exp}
    for _ in range(deg - d0):
        # Extend by one variable and discard reducible monomials.
        nxt = set()
        for m in current:
            for ve in var_exps:
                m2 = m.eadd(ve)
                if m2 not in nxt and not _reducible(m2):
                    nxt.add(m2)
        current = nxt
    return {ring.monomial(*e) for e in current}


def _syz_quotients(U, deg):
    r"""
    Return the cached staircase enumeration underlying ``basis_syzygies``:
    a list of pairs ``(quotient_exponent, syzygy_index)`` describing the
    degree ``deg`` staircase lifts, together with the leading monomial
    exponents of the syzygy generators.

    This is an internal function for sage_periods, and is not meant to be
    called by the user.
    """
    # The staircase walk below depends only on the leading monomials of the
    # syzygy Groebner basis and of the trivial syzygy module, not on their
    # coefficients. These leading monomial patterns are the same at every
    # non-degenerate evaluation point and prime, so the enumerated quotient
    # exponents are cached across calls, keyed by the leading monomial data.
    syzlm_exps = U.syzlm_exps
    key = (syzlm_exps, U.tsyzlm_exps, deg)
    if U.staircase_keys is not None:
        U.staircase_keys.add(key)
    quotients = _staircase_cache.get(key)

    if quotients is None:
        # For each generator a in A, enumerate the admissible staircase monomials above its leading monomial
        # then lift them back to actual multiples of a. This is used to extract degree q
        # pieces of the non-trivial syzygy space A_q appearing in the faster construction of X^r_q.
        quotients = []
        BB = list(U.tsyzlm)

        for i, a in enumerate(U.syz):
            lm = a.lm()

            # Compute the admissible degree-deg monomials divisible by lm but not by the
            # leading monomials already seen.
            D = _diff_stairs(lm, BB, U.vars, deg+1)
            for d in D:
                quotients.append((tuple((d // lm).exponents()[0]), i))

            # Augment the forbidden set so that the output is echelon-like and contains
            # no duplicate leading monomial.
            BB.append(lm)

        _staircase_cache[key] = quotients

    return quotients, syzlm_exps


def _selected_lifts(U, deg):
    r"""
    Return the degree ``deg`` staircase lifts used at this fibre, as a list of
    triples ``(quotient_exponent, syzygy_index, lift_lm)``, where ``lift_lm``
    is the leading monomial exponent of the lift.

    When ``U.profile_active`` is set, only the lifts whose leading monomial
    was recorded as contributing a pivot in the accepted profile are returned.
    Shared by the polynomial (``_basis_syzygies_with_lms``) and linear
    (``LinearEngine.syz_rows``) backends, so both filter identically, before
    any lift is built.

    This is an internal function for sage_periods, and is not meant to be
    called by the user.
    """
    # An armed profile is fixed for this fibre; cache only selected exponents,
    # not coefficient-dependent syzygy polynomials.
    selected = U.filtered_quotients.get(deg) if U.profile_active else None
    if selected is None:
        quotients, syzlm_exps = _syz_quotients(U, deg)
        filt = U.profile.syzlms if U.profile_active else None
        selected = []
        for qe, i in quotients:
            liftlm = tuple(q + s for q, s in zip(qe, syzlm_exps[i]))
            if filt is None or liftlm in filt:
                selected.append((qe, i, liftlm))
        if U.profile_active:
            U.filtered_quotients[deg] = selected
    return selected

